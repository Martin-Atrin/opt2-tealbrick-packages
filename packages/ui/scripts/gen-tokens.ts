/* gen-tokens.ts — generates src/tokens.ts from src/tokens.css. Run: node scripts/gen-tokens.ts [--check]
   Derived from the design lead's tools/gen-tokens-ts.ts (same blocks, same output values). One change: cssVar() maps a
   token name back to its CSS name through a generated table, so names with digits (s8, textH2, shadow1) resolve to the
   real custom property (--tb-s8, --tb-text-h2, --tb-shadow-1); the design version produced --tb-s-8 / --tb-text-h-2.
   tokens.css has three blocks: `:root {` (light base), `[data-theme="dark"] {` (dark base) and
   `:root, [data-theme="dark"] {` (roles and state pairs). `tokens` = light base + roles; `dark` = dark base overrides.
   --check: exit 1 when src/tokens.ts is not what this script would write (the sync test runs the same check). */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export function generate(cssText: string): string {
  const css = cssText.replace(/\/\*[\s\S]*?\*\//g, "");
  const block = (opener: string): [string, string][] => {
    const at = css.indexOf(`${opener} {`);
    if (at < 0) throw new Error(`block not found: ${opener}`);
    const body = css.slice(at, css.indexOf("\n}", at));
    return [...body.matchAll(/--tb-([a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1] ?? "", (m[2] ?? "").trim().replace(/\s+/g, " ")]);
  };
  const light = block("\n:root").concat(block(':root, [data-theme="dark"]'));
  const dark = block('\n[data-theme="dark"]');
  const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  const seen = new Map<string, string>();
  for (const [k] of light) {
    const c = camel(k);
    const prior = seen.get(c);
    if (prior !== undefined && prior !== k) throw new Error(`two CSS names map to one token name: --tb-${prior} and --tb-${k}`);
    seen.set(c, k);
  }
  const deprecatedFrom = light.findIndex(([k]) => k === "surface");
  return `/* Tealbrick design tokens — TypeScript mirror of tokens.css.
   GENERATED by scripts/gen-tokens.ts from src/tokens.css: do not edit by hand (test/tokens.test.ts checks it).
   \`tokens\` = light base + roles/state pairs (values may be var(--tb-*) references, usable in style props).
   \`dark\` = dark base overrides (applied with data-theme="dark"; TBD only for now, C148).
   \`resolved\` / \`resolvedDark\` = literal values for native ports (TBD), Clerk and tests. */

export const tokens = {
${light.map(([k, v], i) => `${deprecatedFrom >= 0 && i >= deprecatedFrom ? "  /** @deprecated 0.1.x alias (removed in 0.3.0) */\n" : ""}  ${camel(k)}: ${JSON.stringify(v)},`).join("\n")}
} as const;

export type TokenName = keyof typeof tokens;

/** Dark base overrides, applied with data-theme="dark" (C148: TBD only for now; Eyal reviews the dark colours). */
export const dark: Partial<Record<TokenName, string>> = {
${dark.map(([k, v]) => `  ${camel(k)}: ${JSON.stringify(v)},`).join("\n")}
};

/** CSS custom property name (without the --tb- prefix) of every token. */
export const cssName: Record<TokenName, string> = {
${light.map(([k]) => `  ${camel(k)}: ${JSON.stringify(k)},`).join("\n")}
};

/** \`var(--tb-<name>)\` for a token, for style props and CSS-in-JS (follows the live theme). */
export const cssVar = (name: TokenName): string => \`var(--tb-\${cssName[name]})\`;

const byCss = Object.fromEntries(Object.entries(cssName).map(([t, c]) => [c, t])) as Record<string, TokenName>;
const resolveIn = (map: Record<string, string>, name: TokenName, seen: Set<string> = new Set()): string => {
  if (seen.has(name)) throw new Error(\`token cycle at \${name}\`);
  seen.add(name);
  const v = map[name];
  if (v === undefined) throw new Error(\`unknown token \${name}\`);
  return v.replace(/var\\(--tb-([a-z0-9-]+)\\)/g, (_, k: string) => {
    const t = byCss[k];
    if (t === undefined) throw new Error(\`unknown token --tb-\${k} in \${name}\`);
    return resolveIn(map, t, new Set(seen));
  });
};
const resolveAll = (map: Record<string, string>) =>
  Object.fromEntries(Object.keys(tokens).map((k) => [k, resolveIn(map, k as TokenName)])) as Record<TokenName, string>;

/** Every token as a literal value, light theme. */
export const resolved = resolveAll({ ...tokens });
/** Every token as a literal value, dark theme. */
export const resolvedDark = resolveAll({ ...tokens, ...dark } as Record<string, string>);
`;
}

if (process.argv[1]?.endsWith("gen-tokens.ts")) {
  const root = join(import.meta.dirname, "..");
  const want = generate(readFileSync(join(root, "src/tokens.css"), "utf8"));
  const file = join(root, "src/tokens.ts");
  if (process.argv.includes("--check")) {
    const have = readFileSync(file, "utf8");
    if (have !== want) {
      console.error("src/tokens.ts is stale: run node scripts/gen-tokens.ts");
      process.exit(1);
    }
    console.log("src/tokens.ts is in sync with src/tokens.css");
  } else {
    writeFileSync(file, want);
    console.log("wrote src/tokens.ts");
  }
}
