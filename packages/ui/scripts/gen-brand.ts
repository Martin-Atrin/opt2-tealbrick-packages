/* gen-brand.ts — writes src/brand-mark.ts: the drawn two-brick mark (assets/brand/logo-mark@3x.png, 108×88, from
   production Website-martin @ c544ef9) as a data: URI, so BrandMark renders under any base path (Portal at `/`, mini
   apps at `/a/<product>/`) without a bundler rule. Run: node scripts/gen-brand.ts [--check] */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
export const brandSource = (): string => {
  const b64 = readFileSync(join(root, "assets/brand/logo-mark@3x.png")).toString("base64");
  return `/* GENERATED by scripts/gen-brand.ts from assets/brand/logo-mark@3x.png (108×88, shown at 36×29): do not edit. */
export const BRAND_MARK_WIDTH = 108;
export const BRAND_MARK_HEIGHT = 88;
export const BRAND_MARK_SRC: string = "data:image/png;base64,${b64}";
`;
};

if (process.argv[1]?.endsWith("gen-brand.ts")) {
  const file = join(root, "src/brand-mark.ts");
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== brandSource()) {
      console.error("src/brand-mark.ts is stale: run node scripts/gen-brand.ts");
      process.exit(1);
    }
    console.log("src/brand-mark.ts is in sync");
  } else {
    writeFileSync(file, brandSource());
    console.log("wrote src/brand-mark.ts");
  }
}
