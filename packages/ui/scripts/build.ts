/* build.ts — builds packages/ui/dist (run from the repo root by `pnpm build`, and by the release Action before npm pack):
   1. tsc → dist/*.js + .d.ts (components, tokens, clerk-appearance, apps, bin/check-system)
   2. dist/tokens.css     = fonts.css (@font-face, self-hosted Nunito) + tokens.css (design source)
   3. dist/components.css = components.css (design source) + kit.css (package additions)
   4. dist/fonts/         = Nunito latin + latin-ext woff2 (variable, 200–1000) + OFL.txt (from @fontsource-variable/nunito)
   No network, no browser: the release build stays deterministic. */
import { execFileSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const root = join(import.meta.dirname, "..");
const dist = join(root, "dist");
const src = (f: string) => readFileSync(join(root, "src", f), "utf8");

if (existsSync(dist)) rmSync(dist, { recursive: true, force: true });
const tsc = join(dirname(createRequire(join(root, "package.json")).resolve("typescript/package.json")), "bin", "tsc");
execFileSync(process.execPath, [tsc, "-p", join(root, "tsconfig.build.json")], { stdio: "inherit" });

const banner = (what: string) =>
  `/* @opt2-tealbrick/ui ${JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version} — ${what}. GENERATED by scripts/build.ts. */\n`;
writeFileSync(join(dist, "tokens.css"), `${banner("tokens.css = fonts.css + tokens.css")}${src("fonts.css")}\n${src("tokens.css")}`);
writeFileSync(join(dist, "components.css"), `${banner("components.css = components.css + kit.css")}${src("components.css")}\n${src("kit.css")}`);
writeFileSync(
  join(dist, "clerk.css"),
  `${banner("clerk.css: Clerk components on the kit look (import after Clerk mounts; unlayered, wins over @layer clerk)")}${src("clerk.css")}`,
);

const fontPkg = dirname(createRequire(join(root, "package.json")).resolve("@fontsource-variable/nunito/package.json"));
mkdirSync(join(dist, "fonts"), { recursive: true });
for (const f of ["nunito-latin-wght-normal.woff2", "nunito-latin-ext-wght-normal.woff2"]) copyFileSync(join(fontPkg, "files", f), join(dist, "fonts", f));
copyFileSync(join(fontPkg, "LICENSE"), join(dist, "fonts", "OFL.txt"));

chmodSync(join(dist, "bin", "check-system.js"), 0o755);
console.log("built packages/ui/dist");
