/* sync-design.ts — copies the approved design source (coordination/design, owned by the design lead) into the package and
   records what was copied in DESIGN-SOURCE.json (sha256 per file). Run locally only (the coordination folder is not in
   this repo): node scripts/sync-design.ts [<design dir>]
   It regenerates src/tokens.ts (scripts/gen-tokens.ts) and checks that the design's own generated tokens.ts
   holds exactly the same values as ours (tokens, dark, resolved, resolvedDark). test/tokens.test.ts re-checks the
   recorded hashes in CI, so a hand edit of a synced file fails the build. */
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { generate } from "./gen-tokens.ts";

const pkg = join(import.meta.dirname, "..");
const design = process.argv[2] ?? join(pkg, "../../../coordination/design");
if (!existsSync(join(design, "tokens.css"))) {
  console.error(`design folder not found: ${design}`);
  process.exit(2);
}

/** [design path, package path, how] — "copy" = byte-identical; "strip-aliases" = copied with the @deprecated 0.1.x
    alias block removed (C133: opt2 is version 0, no compat names); "derived" = adapted by hand, hash recorded only */
type How = "copy" | "strip-aliases" | "derived";
const FILES: [string, string, How][] = [
  ["tokens.css", "src/tokens.css", "strip-aliases"],
  ["components.css", "src/components.css", "copy"],
  ["clerk-appearance.ts", "src/clerk-appearance.ts", "copy"],
  ["tokens.ts", "", "derived"], // regenerated by scripts/gen-tokens.ts (fixed cssVar), values compared below
  ["tools/gen-tokens-ts.ts", "scripts/gen-tokens.ts", "derived"],
  ["tools/check-system.ts", "src/bin/check-system.ts", "derived"],
  ["tools/check-contrast.ts", "scripts/check-contrast.ts", "derived"],
  ["tools/screens.ts", "scripts/check-rendered.ts", "derived"],
  ["tools/png.ts", "scripts/png.ts", "copy"],
  ["assets/apps.ts", "src/apps.ts", "derived"],
  ["assets/brand/PROVENANCE.md", "assets/brand/PROVENANCE.md", "copy"],
  ["assets/brand/logo-mark@3x.png", "assets/brand/logo-mark@3x.png", "copy"],
  ["assets/brand/logo-32.png", "assets/brand/logo-32.png", "copy"],
  ["assets/brand/logo-48.png", "assets/brand/logo-48.png", "copy"],
  ["assets/brand/logo-apple-180.png", "assets/brand/logo-apple-180.png", "copy"],
];
/** the apps the kit has art for: the opt2 apps with a product id (assets/apps.ts byOpt2Id) plus Observer, Live Artifacts and Creative;
    the other three stills (Mesh Trust Topology, Local Runtime Bridge, Remote Setup) have no opt2 app yet */
const STILLS = [
  "knowledge",
  "marketplace",
  "work-ethic-kanban",
  "operator-inbox",
  "rules-approvals",
  "organization-plane",
  "evolution-workflow-runtime",
  "observer-backfill",
  "live-artifacts",
  "open-design",
];
for (const slug of STILLS) for (const d of ["1x", "2x"]) FILES.push([`assets/apps/${slug}@${d}.webp`, `assets/apps/${slug}@${d}.webp`, "copy"]);

/** Removes the "@deprecated 0.1.x aliases" block (comment line up to the end of its rule block). */
export const stripAliases = (css: string): string => {
  const at = css.indexOf("  /* @deprecated 0.1.x aliases");
  if (at < 0) return css;
  const end = css.indexOf("\n}", at);
  return css.slice(0, at).replace(/\n+$/, "") + css.slice(end);
};
const sha = (b: Buffer | string) => createHash("sha256").update(b).digest("hex");
const record: Record<string, { sha256: string; to: string; how: How; pkgSha256?: string }> = {};
for (const [from, to, how] of FILES) {
  const src = join(design, from);
  const bytes = readFileSync(src);
  if (how === "copy") copyFileSync(src, join(pkg, to));
  if (how === "strip-aliases") writeFileSync(join(pkg, to), stripAliases(bytes.toString("utf8")));
  record[from] = { sha256: sha(bytes), to, how, ...(how === "derived" ? {} : { pkgSha256: sha(readFileSync(join(pkg, to))) }) };
}
writeFileSync(
  join(pkg, "DESIGN-SOURCE.json"),
  `${JSON.stringify({ source: "coordination/design (opt2 design lead)", synced: new Date().toISOString(), files: record }, null, 2)}\n`,
);

// regenerate src/tokens.ts, then check that the design's generated tokens.ts and ours hold the same tokens
writeFileSync(join(pkg, "src/tokens.ts"), generate(readFileSync(join(pkg, "src/tokens.css"), "utf8")));
const ours = await import(pathToFileURL(join(pkg, "src/tokens.ts")).href);
const theirs = await import(pathToFileURL(join(design, "tokens.ts")).href);
// ours = the design's tokens minus the stripped 0.1.x aliases; every value we keep must be identical
const ALIASES =
  /^(surface|white|canvas|accent|veil|fontSans|primary|primaryHover|onPrimary|radius|radiusFocus|radiusPillAsIs|shadow1|shadow2|ok|progress|action|blocked|neutral)$/;
for (const k of ["tokens", "dark", "resolved", "resolvedDark"]) {
  const a = ours[k] as Record<string, string>;
  const b = theirs[k] as Record<string, string>;
  const missing = Object.keys(b).filter((n) => !(n in a) && !ALIASES.test(n));
  const differ = Object.keys(a).filter((n) => a[n] !== b[n]);
  if (missing.length || differ.length) {
    console.error(`tokens.ts mismatch in "${k}": missing ${missing.join(",")} differ ${differ.join(",")}`);
    process.exit(1);
  }
}
console.log(`synced ${FILES.length} files from ${design}; tokens.ts values equal the design's`);
