/* sync-design.ts — copies the approved design source (coordination/design, owned by the design lead) into the package and
   records what was copied in DESIGN-SOURCE.json (sha256 per file). Run locally only (the coordination folder is not in
   this repo): node scripts/sync-design.ts [<design dir>]
   It regenerates src/tokens.ts (scripts/gen-tokens.ts) and checks that the design's own generated tokens.ts
   holds exactly the same values as ours (tokens, dark, resolved, resolvedDark). test/tokens.test.ts re-checks the
   recorded hashes in CI, so a hand edit of a synced file fails the build. */
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { generate } from "./gen-tokens.ts";

const pkg = join(import.meta.dirname, "..");
const design = process.argv[2] ?? join(pkg, "../../../coordination/design");
if (!existsSync(join(design, "tokens.css"))) {
  console.error(`design folder not found: ${design}`);
  process.exit(2);
}

/** [design path, package path, how] — "copy" = byte-identical; "derived" = adapted by hand, hash recorded for traceability */
const FILES: [string, string, "copy" | "derived"][] = [
  ["tokens.css", "src/tokens.css", "copy"],
  ["components.css", "src/components.css", "copy"],
  ["clerk-appearance.ts", "src/clerk-appearance.ts", "copy"],
  ["tokens.ts", "", "derived"], // regenerated by scripts/gen-tokens.ts (fixed cssVar), values compared below
  ["tools/gen-tokens-ts.ts", "scripts/gen-tokens.ts", "derived"],
  ["tools/check-system.ts", "src/bin/check-system.ts", "derived"],
  ["tools/check-contrast.ts", "scripts/check-contrast.ts", "derived"],
  ["tools/screens.ts", "scripts/check-rendered.ts", "derived"],
  ["tools/png.ts", "scripts/png.ts", "copy"],
  ["assets/apps.ts", "src/apps.ts", "derived"],
  ["assets/brand/PROVENANCE.md", "assets/brand/PROVENANCE.md", "copy"],
  ["assets/brand/logo-mark@3x.png", "assets/brand/logo-mark@3x.png", "copy"],
  ["assets/brand/logo-32.png", "assets/brand/logo-32.png", "copy"],
  ["assets/brand/logo-48.png", "assets/brand/logo-48.png", "copy"],
  ["assets/brand/logo-apple-180.png", "assets/brand/logo-apple-180.png", "copy"],
];
/** the opt2 apps that have a product id (assets/apps.ts byOpt2Id); the other six stills have no opt2 app yet */
const STILLS = ["knowledge", "marketplace", "work-ethic-kanban", "operator-inbox", "rules-approvals", "organization-plane", "evolution-workflow-runtime"];
for (const slug of STILLS)
  for (const d of ["1x", "2x"]) FILES.push([`assets/apps/${slug}@${d}.webp`, `assets/apps/${slug}@${d}.webp`, "copy"]);

const sha = (p: string) => createHash("sha256").update(readFileSync(p)).digest("hex");
const record: Record<string, { sha256: string; to: string; how: string }> = {};
for (const [from, to, how] of FILES) {
  const src = join(design, from);
  if (how === "copy") copyFileSync(src, join(pkg, to));
  record[from] = { sha256: sha(src), to, how };
}
writeFileSync(join(pkg, "DESIGN-SOURCE.json"), `${JSON.stringify({ source: "coordination/design (opt2 design lead)", synced: new Date().toISOString(), files: record }, null, 2)}\n`);

// regenerate src/tokens.ts, then check that the design's generated tokens.ts and ours hold the same tokens
writeFileSync(join(pkg, "src/tokens.ts"), generate(readFileSync(join(pkg, "src/tokens.css"), "utf8")));
const ours = await import(pathToFileURL(join(pkg, "src/tokens.ts")).href);
const theirs = await import(pathToFileURL(join(design, "tokens.ts")).href);
for (const k of ["tokens", "dark", "resolved", "resolvedDark"]) {
  const a = JSON.stringify(ours[k]);
  const b = JSON.stringify(theirs[k]);
  if (a !== b) {
    console.error(`tokens.ts mismatch in "${k}": run node scripts/gen-tokens.ts after syncing tokens.css`);
    process.exit(1);
  }
}
console.log(`synced ${FILES.length} files from ${design}; tokens.ts values equal the design's`);
