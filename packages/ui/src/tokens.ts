/** `var(--tb-<name>)` for a token, for style props and CSS-in-JS (follows the live theme). */
export const cssVar = (name: TokenName): string => `var(--tb-${cssName[name]})`;

const byCss = Object.fromEntries(Object.entries(cssName).map(([t, c]) => [c, t])) as Record<string, TokenName>;
const resolveIn = (map: Record<string, string>, name: TokenName, seen: Set<string> = new Set()): string => {
  if (seen.has(name)) throw new Error(`token cycle at ${name}`);
  seen.add(name);
  const v = map[name];
  if (v === undefined) throw new Error(`unknown token ${name}`);
  return v.replace(/var\(--tb-([a-z0-9-]+)\)/g, (_, k: string) => {
    const t = byCss[k];
    if (t === undefined) throw new Error(`unknown token --tb-${k} in ${name}`);
    return resolveIn(map, t, new Set(seen));
  });
};
const resolveAll = (map: Record<string, string>) =>
  Object.fromEntries(Object.keys(tokens).map((k) => [k, resolveIn(map, k as TokenName)])) as Record<TokenName, string>;

/** Every token as a literal value, light theme. */
export const resolved = resolveAll({ ...tokens });
/** Every token as a literal value, dark theme. */
export const resolvedDark = resolveAll({ ...tokens, ...dark } as Record<string, string>);
